/** Region window in degrees. */
export const BOUNDS = { lon0: -19, lon1: 53, lat0: -36, lat1: 38 };

const D2R = Math.PI / 180;
const mercY = (lat: number) => Math.log(Math.tan(Math.PI / 4 + (lat * D2R) / 2));
const X0 = BOUNDS.lon0 * D2R;
const Y1 = mercY(BOUNDS.lat1);
const SCALE = 1000 / ((BOUNDS.lon1 - BOUNDS.lon0) * D2R);

/** Project a real coordinate into the sheet's own coordinate system. */
export function project(lon: number, lat: number): [number, number] {
  return [(lon * D2R - X0) * SCALE, (Y1 - mercY(lat)) * SCALE];
}

/**
 * A true circle on the ground, drawn as it really falls on this projection.
 * Mercator scale grows with latitude, so a constant-distance ring is not a
 * circle on the sheet; walking real great-circle bearings keeps the stated
 * kilometres honest instead of drawing a convenient circle.
 */
export function geodesicRing(
  lon: number,
  lat: number,
  km: number,
  steps = 96,
): string {
  const R = 6371;
  const d = km / R;
  const la1 = lat * D2R;
  const lo1 = lon * D2R;
  const pts: string[] = [];
  for (let i = 0; i <= steps; i++) {
    const brg = (i / steps) * 2 * Math.PI;
    const la2 = Math.asin(
      Math.sin(la1) * Math.cos(d) + Math.cos(la1) * Math.sin(d) * Math.cos(brg),
    );
    const lo2 =
      lo1 +
      Math.atan2(
        Math.sin(brg) * Math.sin(d) * Math.cos(la1),
        Math.cos(d) - Math.sin(la1) * Math.sin(la2),
      );
    const [x, y] = project(lo2 / D2R, la2 / D2R);
    pts.push(`${x.toFixed(1)} ${y.toFixed(1)}`);
  }
  return "M" + pts.join("L") + "Z";
}

/** Un point à distance et azimut réels depuis une origine, projeté. */
export function geodesicPoint(
  lon: number,
  lat: number,
  km: number,
  bearingDeg: number,
): [number, number] {
  const R = 6371;
  const d = km / R;
  const la1 = lat * D2R;
  const lo1 = lon * D2R;
  const brg = bearingDeg * D2R;
  const la2 = Math.asin(
    Math.sin(la1) * Math.cos(d) + Math.cos(la1) * Math.sin(d) * Math.cos(brg),
  );
  const lo2 =
    lo1 +
    Math.atan2(
      Math.sin(brg) * Math.sin(d) * Math.cos(la1),
      Math.cos(d) - Math.sin(la1) * Math.sin(la2),
    );
  return project(lo2 / D2R, la2 / D2R);
}

